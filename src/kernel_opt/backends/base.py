from typing import Protocol
class BackendAdapter(Protocol):
 backend_id:str
 def discover_devices(self)->list[dict]: ...
 def probe_capabilities(self,target:dict)->dict: ...
 def fetch_architecture_sources(self,target:dict)->list[dict]: ...
 def validate_kernel_design(self,spec:dict,design:dict)->dict: ...
 def compile(self,candidate:dict,timeout_s:int)->dict: ...
 def run_reference_check(self,candidate:dict,spec:dict,timeout_s:int)->dict: ...
 def benchmark(self,candidate:dict,plan:dict,timeout_s:int)->dict: ...
 def profile(self,candidate:dict,plan:dict,timeout_s:int)->dict: ...
 def normalize_metrics(self,raw_artifacts:list[str])->list[dict]: ...
class NotConfiguredAdapter:
 backend_id="not-configured"
 def _n(self): return {"status":"NOT_CONFIGURED","provenance_kind":"estimated"}
 def discover_devices(self): return []
 def probe_capabilities(self,target): return self._n()
 def fetch_architecture_sources(self,target): return []
 def validate_kernel_design(self,spec,design): return self._n()
 def compile(self,candidate,timeout_s): return self._n()
 def run_reference_check(self,candidate,spec,timeout_s): return self._n()
 def benchmark(self,candidate,plan,timeout_s): return self._n()
 def profile(self,candidate,plan,timeout_s): return self._n()
 def normalize_metrics(self,raw_artifacts): return []
